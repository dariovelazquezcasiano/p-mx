      $this->count_ger = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][1];
      if ($_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['SC_Ind_Groupby'] == "sc_free_total")
      {
          $this->sum_a = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][2];
          $this->sum_ar = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][3];
          $this->sum_m = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][4];
          $this->sum_b2 = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][5];
          $this->sum_b3 = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][6];
          $this->sum_b4 = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][7];
          $this->sum_c2 = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][8];
          $this->sum_c3 = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][9];
