      }
      if (!isset($CasetaAforo) && isset($casetaaforo)) 
      {
         $CasetaAforo = $casetaaforo;
      }
      if (isset($CasetaAforo)) 
      {
          $_SESSION['CasetaAforo'] = $CasetaAforo;
