          $this->sum_c5 = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][11];
          $this->sum_c6 = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][12];
          $this->sum_c7 = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][13];
          $this->sum_c8 = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][14];
          $this->sum_c9 = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][15];
          $this->sum_exe = $_SESSION['sc_session'][$this->Ini->sc_page]['grid_trafico']['tot_geral'][16];
